'use strict';
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const out = path.join(root, 'dist', 'h5');
const files = ['index.html', 'styles.css', 'game.js', 'art.js', 'app.js'];
const G = require('../game.js');
const solutions = require('../tests/solutions.cjs');
G.levels.forEach((level, i) => level.orders.forEach(order => assert.equal(G.execute(solutions[i], order, level.blocks).success, true)));
fs.mkdirSync(out, { recursive: true });
for (const name of files) fs.copyFileSync(path.join(root, name), path.join(out, name));
const html = fs.readFileSync(path.join(out, 'index.html'), 'utf8');
for (const [, ref] of html.matchAll(/(?:src|href)="([^"]+)"/g)) assert.ok(ref === './' || files.includes(ref), `無法打包的資源：${ref}`);
let standalone = html.replace('<link rel="stylesheet" href="styles.css">', () => `<style>${fs.readFileSync(path.join(root, 'styles.css'), 'utf8')}</style>`);
for (const name of ['game.js', 'art.js', 'app.js']) standalone = standalone.replace(`<script src="${name}" defer></script>`, '');
const scripts = ['game.js', 'art.js', 'app.js'].map(name => `<script>${fs.readFileSync(path.join(root, name), 'utf8')}</script>`).join('\n');
standalone = standalone.replace('</body>', () => scripts + '\n</body>');
fs.writeFileSync(path.join(root, 'dist', 'monster-snack.html'), standalone);
console.log(`H5 已輸出：${out}（5 個檔案，無外部依賴）；另附 dist/monster-snack.html 單檔版`);
