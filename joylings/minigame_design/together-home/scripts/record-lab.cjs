const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const levels=require('../lab-levels.js'), G=require('../core.js').create(levels,require('../lab-rules.js')(levels));
const Input=require('../input.js'),{playLab}=require('../tests/play-lab.cjs');
async function record(){
  const tapes={};
  for(const l of levels){
    if(process.env.LAB_LEVEL && l.id!==Number(process.env.LAB_LEVEL)-1)continue;
    let state=G.fresh(l.id),frames=0;const actions=[],keyboard=Input.create();
    await playLab({read:async()=>state,mark:async name=>console.log(name,JSON.stringify({players:state.players.map(p=>[p.x,p.y]),boxes:state.boxes.map(b=>b.x),rafts:state.rafts,echoes:state.echoes,keys:state.collected})),tick:async(n,commands)=>{
      for(let i=0;i<n&&!state.won;i++){
        const bits=Input.mask(commands.map(c=>({...c,jump:i===0&&c.jump})));
        keyboard.setMask(bits);state=G.step(state,keyboard.read());keyboard.consume();
        assert.ok(!state.failed,JSON.stringify(state));assert.ok(++frames<120*600);
        const previous=actions.at(-1);if(previous?.[1]===bits)previous[0]++;else actions.push([1,bits]);
      }
    }},l);
    assert.ok(state.won);tapes[l.saveKey]={frames,actions};
    console.log(`${l.id+1} ${l.name}: ${(frames/120).toFixed(1)} 秒，${actions.length} 段按鍵`);
  }
  if(process.env.LAB_LEVEL)return;
  const output='// Generated by npm run record:lab; ordinary key inputs only.\n(function(root){\nconst data='+JSON.stringify({fps:120,levels:tapes})+';\n'+"if(typeof module!=='undefined')module.exports=data;else root.TogetherSolutions=data;\n})(globalThis);\n";
  const target=path.join(__dirname,'../lab-solutions.js');
  if(process.argv.includes('--check'))assert.equal(fs.readFileSync(target,'utf8').replace(/\r\n/g,'\n'),output);else fs.writeFileSync(target,output);
}
record().catch(e=>{console.error(e);process.exitCode=1;});
