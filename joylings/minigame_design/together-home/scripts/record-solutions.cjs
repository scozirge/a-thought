// Record only ordinary key states. No positions, key grants or world overrides.
const fs = require('node:fs'), path = require('node:path'), assert = require('node:assert/strict');
const G = require('../core.js'), Input = require('../input.js'), { playLevel } = require('../tests/play-level.cjs');
async function record() {
  const levels = {};
  for (const l of G.levels) {
    let state = G.fresh(l.id), frames = 0;
    const keyboard = Input.create(), actions = [];
    await playLevel({ read: async () => state, tick: async (n, commands) => {
      for (let i = 0; i < n && !state.won; i++) {
        const bits = Input.mask(commands.map(c => ({ ...c, jump: i === 0 && c.jump, special: i === 0 && c.special })));
        keyboard.setMask(bits);
        state = G.step(state, keyboard.read()); keyboard.consume();
        assert.ok(!state.failed, `第 ${l.id + 1} 關掉落`);
        assert.ok(++frames < 120 * 600, `第 ${l.id + 1} 關超時`);
        const previous = actions.at(-1);
        if (previous?.[1] === bits) previous[0]++; else actions.push([1, bits]);
      }
    } }, l);
    assert.ok(state.won && state.collected.every(Boolean) && state.players.every(p => p.exited));
    levels[l.saveKey] = { frames, actions };
    console.log(`第 ${l.id + 1} 關：${frames} 步，${(frames / 120).toFixed(1)} 秒，${actions.length} 段按鍵`);
  }
  const data = { fps: 120, levels };
  const output = '// Generated by npm run record:solutions. Every frame uses normal input.js key transitions.\n' +
    '(function(root){\nconst data=' + JSON.stringify(data, null, 0) + ';\n' +
    "if(typeof module!=='undefined')module.exports=data;else root.TogetherSolutions=data;\n})(globalThis);\n";
  const target = path.join(__dirname, '../solutions.js');
  if (process.argv.includes('--check')) assert.equal(fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n'), output, '關卡或解法變更後，請執行 npm run record:solutions');
  else fs.writeFileSync(target, output);
}
record().catch(error => { console.error(error); process.exitCode = 1; });
